ROBOTS: dict[str, RobotSpec] = {spec.name: spec for spec in (KUKA_IIWA14, FLEXIV_RIZON4)}


def get_robot_spec(name: str) -> RobotSpec:
    try:
        return ROBOTS[name]
    except KeyError:
        raise ValueError(f"Unknown robot {name!r}; expected one of {sorted(ROBOTS)}") from None


