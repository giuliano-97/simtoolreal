"""Robot (arm + left Sharpa HA4 hand) specifications shared by the sim backends.

Each spec pins everything that depends on the arm: URDF, joint and link names,
default poses, arm PD gains, base placement, and the palm-center offset. The
hand (joint names, order, gains) is the same for every arm. Pure Python so the
deployment stack can import it without a simulator.

Select a robot in Isaac Sim with ``env.assets.robot=<name>``.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

# Sharpa HA4 (left) joints in policy order. Shared by every arm.
LEFT_SHARPA_HAND_JOINT_NAMES: tuple[str, ...] = (
    "left_1_thumb_CMC_FE", "left_thumb_CMC_AA", "left_thumb_MCP_FE",
    "left_thumb_MCP_AA", "left_thumb_IP",
    "left_2_index_MCP_FE", "left_index_MCP_AA", "left_index_PIP", "left_index_DIP",
    "left_3_middle_MCP_FE", "left_middle_MCP_AA", "left_middle_PIP", "left_middle_DIP",
    "left_4_ring_MCP_FE", "left_ring_MCP_AA", "left_ring_PIP", "left_ring_DIP",
    "left_5_pinky_CMC", "left_pinky_MCP_FE", "left_pinky_MCP_AA",
    "left_pinky_PIP", "left_pinky_DIP",
)
NUM_ARM_JOINTS = 7


@dataclass(frozen=True)
class RobotSpec:
    name: str
    # Repo-relative path of the combined arm + hand URDF.
    urdf_path: str
    # Arm joints in policy order.
    arm_joint_names: tuple[str, ...]
    # Arm links from base to last link. Fixed joints are merged on import, so the
    # last link carries the mount and hand palm and acts as the palm body.
    arm_link_names: tuple[str, ...]
    # Training default pose, and the raised variant used for DexToolBench eval.
    arm_default_joint_pos: tuple[float, ...]
    arm_start_higher_joint_pos: tuple[float, ...]
    arm_joint_stiffness: tuple[float, ...]
    arm_joint_damping: tuple[float, ...]
    # Robot base pose in the env frame (the table is centered at the origin).
    base_pos: tuple[float, float, float]
    base_quat_xyzw: tuple[float, float, float, float]
    # Palm center in the palm-body frame (the policy observes this point).
    palm_center_offset: tuple[float, float, float]

    def __post_init__(self) -> None:
        for field in (
            "arm_joint_names", "arm_default_joint_pos", "arm_start_higher_joint_pos",
            "arm_joint_stiffness", "arm_joint_damping",
        ):
            assert len(getattr(self, field)) == NUM_ARM_JOINTS, f"{self.name}.{field}"
        assert len(self.arm_link_names) == NUM_ARM_JOINTS + 1, f"{self.name}.arm_link_names"

    @property
    def palm_body_name(self) -> str:
        return self.arm_link_names[-1]

    @property
    def joint_names_canonical(self) -> tuple[str, ...]:
        return self.arm_joint_names + LEFT_SHARPA_HAND_JOINT_NAMES

    def arm_joint_dict(self, values: tuple[float, ...]) -> dict[str, float]:
        return dict(zip(self.arm_joint_names, values))


